#include <iostream>
#include <vector>
using namespace std;

/* ==========================================================================
   [ 핵심 원리: 왜 나머지가 같은 것 중 2개를 뽑을까? ]
   ==========================================================================

   1. 부분 구간의 합 (Prefix Sum)
   배열의 i번째부터 j번째까지의 합은 누적 합 배열 S로 표현합니다.
   => Sum(i, j) = S[j] - S[i-1]

   2. 문제의 조건 (M으로 나누어 떨어짐)
   구간의 합이 M의 배수이므로, M으로 나눈 나머지가 0이어야 합니다.
   => (S[j] - S[i-1]) % M == 0

   3. 나머지 연산의 성질 적용
   위 식을 풀어서 이항하면 아래와 같은 결론이 나옵니다.
   => S[j] % M == S[i-1] % M

   4. 결론: 조합 (nC2) 계산
   - 즉, "누적 합을 M으로 나눈 나머지가 같은 두 지점"을 고르면,
     그 사이 구간의 합은 무조건 M으로 나누어 떨어집니다.
   - 특정 나머지 값이 총 n번 등장했다면, 그 중 2개를 고르는 경우의 수
   => nC2 = n * (n - 1) / 2

   ※ 예외 처리:
   누적 합 자체의 나머지가 0인 경우는 시작점부터 해당 지점까지의
   구간 자체가 이미 M의 배수이므로 정답 카운트에 더해주어야 합니다.
   ========================================================================== */

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int N, M;
    cin >> N >> M;

    long long sum = 0;
    long long cnt = 0;

    // 나머지가 0 ~ M-1인 것들이 각각 몇 번 나왔는지 세는 배열
    vector<long long> remain_count(M, 0);

    for (int i = 0; i < N; i++)
    {
        int num;
        cin >> num;
        sum += num;
        int remainder = sum % M;

        if (remainder == 0)
        {
            cnt++;
        }
        remain_count[remainder]++;
    }

    for (int i = 0; i < M; i++)
    {
        if (remain_count[i] > 1)
        {
            // remain_count[i] 개 중 2개를 뽑는 경우의 수를 계산해서 cnt에 더하세요.
            // 힌트: nC2 = n * (n - 1) / 2
            long long n = remain_count[i];
            cnt += n * (n - 1) / 2;
        }
    }
    cout << cnt << "\n";
    return 0;
}