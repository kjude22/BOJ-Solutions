#include <iostream>
using namespace std;

int C[30][30];

int main()
{
    for (int i = 0; i < 30; i++)
    {
        C[i][0] = 1;
        C[i][i] = 1;
        for (int j = 0; j < i; j++)
        {
            C[i][j] = C[i - 1][j - 1] + C[i - 1][j];
        }
    }

    int T;
    cin >> T;
    while (T--)
    {
        int N, M;
        cin >> N >> M; // M >= N

        cout << C[M][N] << "\n";
    }
    return 0;
}