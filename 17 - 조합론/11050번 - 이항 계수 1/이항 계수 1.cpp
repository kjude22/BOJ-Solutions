#include <iostream>
using namespace std;
/*
    <조합론>
    파스칼 삼각형 성질을 이용
    * C[n][k] = C[n-1][k-1] + C[n-1][k]

*/
int C[11][11];

int main()
{
    /* 파스칼 삼각형 생성 */
    for (int i = 0; i < 11; i++)
    {
        C[i][0] = 1;
        C[i][i] = 1;
        for (int j = 1; j < i; j++)
        {
            C[i][j] = C[i - 1][j - 1] + C[i - 1][j];
        }
    }

    int N, K;
    cin >> N >> K;

    cout << C[N][K] << "\n";
    return 0;
}