#include <iostream>
using namespace std;

int main()
{
    string s;
    cin >> s;

    int cnt = 0;
    int dial[] = {2, 2, 2,
                  3, 3, 3,
                  4, 4, 4,
                  5, 5, 5,
                  6, 6, 6,
                  7, 7, 7, 7, // 7, 9번 다이얼은 4!!
                  8, 8, 8,
                  9, 9, 9, 9};

    for (int i = 0; i < s.length(); i++)
    {
        int n = s[i] - 'A';
        cnt += (dial[n] + 1);
    }

    cout << cnt << endl;
}