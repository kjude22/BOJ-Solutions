#include <iostream>
using namespace std;

/* 일단 계산과정 적어봐!! */
int main()
{
    int A, B, V;
    cin >> A >> B >> V;
    // A * (d) - B * (d - 1) = V
    int d;
    d = (V - B + (A - B - 1)) / (A - B);
    cout << d << endl;
    return 0;
}