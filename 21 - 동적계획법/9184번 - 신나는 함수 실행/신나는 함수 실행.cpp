#include <iostream>
using namespace std;

int dp[101][101][101];

int w(int a, int b, int c)
{

    if (a > 20 || b > 20 || c > 20)
    {
        if (dp[a + 50][b + 50][c + 50] == -1)
        {
            dp[a + 50][b + 50][c + 50] = w(20, 20, 20);
        }
        return dp[a + 50][b + 50][c + 50];
    }

    for (int i = 1; i <= a; i++)
    {
        for (int j = 1; j <= b; j++)
        {
            for (int k = 1; k <= c; k++)
            {
                if (i < j && j < k)
                {
                    dp[i + 50][j + 50][k + 50] =
                        dp[i + 50][j + 50][k - 1 + 50] + dp[i + 50][j - 1 + 50][k - 1 + 50] - dp[i + 50][j - 1 + 50][k + 50];
                }
                else
                {
                    dp[i + 50][j + 50][k + 50] =
                        dp[i - 1 + 50][j + 50][k + 50] + dp[i - 1 + 50][j - 1 + 50][k + 50] + dp[i - 1 + 50][j + 50][k - 1 + 50] - dp[i - 1 + 50][j - 1 + 50][k - 1 + 50];
                }
            }
        }
    }
    return dp[a + 50][b + 50][c + 50];
}

int main()
{
    for (int i = -50; i <= 50; i++)
        for (int j = -50; j <= 50; j++)
            for (int k = -50; k <= 50; k++)
            {
                if (i <= 0 || j <= 0 || k <= 0)
                {
                    dp[i + 50][j + 50][k + 50] = 1;
                }
                else
                {
                    dp[i + 50][j + 50][k + 50] = -1;
                }
            }

    while (1)
    {
        int a, b, c;
        cin >> a >> b >> c;

        if (a == -1 && b == -1 && c == -1)
            break;

        cout << "w(" << a << ", " << b << ", " << c << ") = " << w(a, b, c) << "\n";
    }
    return 0;
}